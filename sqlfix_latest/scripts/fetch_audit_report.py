"""Build docs/FETCH_AUDIT.md from artifacts/fetch_audit/{audit,benchG,benchF}.json (written by scripts/fetch_audit.py)."""
import json
import math
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def wilson(k, n, z=1.96):
    if not n:
        return "n/a"
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{100 * p:.1f}% (95% CI {100 * (c - h):.1f}-{100 * (c + h):.1f})"


def pct(k, n):
    return f"{100 * k / n:.1f}%" if n else "n/a"


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def write_report(out_dir):
    from scripts.fetch_audit import arm_metrics
    audit = json.load(open(os.path.join(out_dir, "audit.json")))["rows"]
    n = len(audit)
    L = ["# Website acquisition: failure audit and before/after benchmark", "",
         "Generated by `python scripts/fetch_audit.py report` from `artifacts/fetch_audit/*.json`. Free path only: no provider keys were set, so paid providers (Firecrawl, Serper, Google Places) were not exercised.", "",
         f"## 1. Failure audit ({n} real business sites)", "",
         "Sites: Overture Maps places with a website, sampled across 9 US city/industry combinations that no earlier run had visited (`scripts/fetch_audit.py collect`). Each site was fetched once with the direct pooled HTTP provider (plus the free same-site fixes: JS/meta redirect, root path, scheme/www flip), classified by `fetch_classify.py`, then every site that failed was retried with Scrapling and with the local Playwright browser to measure what each provider recovers.", ""]
    cat = Counter(r["direct"]["category"] for r in audit)
    usable = sum(r["direct"]["usable"] for r in audit)
    L += [f"Direct fetch usable: **{wilson(usable, n)}**.", "", table(["Direct-fetch verdict", "Sites", "Share"], [(k, v, pct(v, n)) for k, v in cat.most_common()]), ""]
    groups = {"Bot protection / refusal (cloudflare, sgcaptcha, datadome, akamai, incapsula, access_denied, http_403, http_429, js_challenge, recaptcha, hcaptcha)": {"cloudflare", "sgcaptcha", "datadome", "akamai", "incapsula", "access_denied", "http_403", "http_429", "js_challenge", "recaptcha", "hcaptcha", "perimeterx", "sucuri"},
              "Dead site (dns, http_404, parked)": {"dns", "http_404", "parked"}, "Network (timeout, tls, connect, disconnect)": {"timeout", "tls", "connect", "disconnect"},
              "Server error / other HTTP (http_5xx, http_4xx)": {"http_5xx", "http_4xx"}, "Needs rendering or redirect (js_shell, redirect_stub, empty_body)": {"js_shell", "redirect_stub", "empty_body"}}
    rows = []
    for name, cs in groups.items():
        k = sum(v for c, v in cat.items() if c in cs)
        unusable = sum(1 for r in audit if r["direct"]["category"] in cs and not r["direct"]["usable"])
        rows.append((name, k, pct(k, n), unusable))
    L += ["### Failure causes grouped", "", table(["Cause", "Sites", "Share of all", "Unusable"], rows), ""]
    by_status = Counter(str(r["direct"]["status"]) for r in audit if not r["direct"]["usable"])
    L += ["### Unusable sites by HTTP status (None = no HTTP response)", "", table(["Status", "Sites"], by_status.most_common()), ""]
    srv = Counter((r["direct"].get("server") or "unknown").split("/")[0].lower() for r in audit if r["direct"]["kind"] in ("challenge", "rate_limit"))
    L += ["### Protection by server header (challenged sites)", "", table(["Server", "Sites"], srv.most_common(8)), ""]
    prov = []
    for p in ("scrapling", "browser"):
        tried = [r for r in audit if p in r["others"]]
        ok = [r for r in tried if r["others"][p]["usable"]]
        by = Counter(r["direct"]["category"] for r in ok)
        prov.append((p, len(tried), len(ok), pct(len(ok), len(tried)), dict(by)))
    probe = [r for r in audit if "browser_probe" in r["others"]]
    pk = [r for r in probe if r["others"]["browser_probe"]["usable"]]
    L += ["### What each fallback provider recovers (sites the direct fetch could not use)", "", table(["Provider", "Tried", "Recovered", "Rate", "Recovered by direct verdict"], prov), "",
          f"Measurement only: a real headless browser on {len(probe)} challenged sites got a usable page on {len(pk)} (an earlier run on a different 450-site sample found 2 of 25, both plain 403/'access denied' responses). The engine does not do this: 403/429/challenge responses stop the cascade, set a cooldown and go to the human-verification queue.", "",
          "Reading: Scrapling recovers almost nothing the direct fetch misses. The browser's value depends on how many sites drop plain HTTP clients: an earlier run on a different 450-site sample (direct usable 72.4%) had the browser recover 24 of 97 failed sites (16 of 19 server disconnects, 7 of 9 5xx answers, 1 empty body) and Scrapling 1 of 124; in the sample above there were only 7 disconnects and 1 5xx, so it recovers little. The engine's starting priors (`fetch_engine.History.PRIORS`) come from that earlier run and are replaced by live history as attempts accumulate.", ""]
    dom = defaultdict(int)
    for r in audit:
        if not r["direct"]["usable"]:
            dom[(r["domain"], r["direct"]["category"])] += 1
    L += ["### Problem domains (first 15 of the unusable sites)", "", table(["Domain", "Verdict"], [k for k in list(dom)[:15]]), ""]

    def load(name):
        try:
            return json.load(open(os.path.join(out_dir, name)))
        except FileNotFoundError:
            return None
    G = load("benchG.json")
    L += ["## 2. Before/after benchmark", "",
          "Three arms on **disjoint** random slices of fresh sites (266 each), so no arm is throttled by another arm's earlier visits (sites remember repeated visits: an earlier paired run on the same sites produced many more SiteGround captcha pages in the arm that ran last).", "",
          "* **legacy**: Scrapling-first fetch (`LEADX_FETCH_FAST=0`, engine off), the behaviour before the earlier optimization.",
          "* **fast**: pooled-HTTP-first, engine off (the state at the start of this change).",
          "* **engine**: acquisition engine + alternative-source recovery (this change).", "",
          "Definitions (kept separate on purpose):", "",
          "* *Website fetch success*: the homepage came back as a real page (not a challenge, error or empty body), judged by the same classifier for every arm.",
          "* *Acquisition (strict)*: fetch success + **recovered** leads (an identity-matched alternative source gave an email or phone the lead did not have).",
          "* *Acquisition incl. corroborated*: also counts leads where an alternative source confirmed the contact discovery already had (adds confidence, no new data).",
          "* *Contact incl. discovery hints*: any lead that has an email or phone from its discovery record or any source. Almost every lead has this before any fetch, so it does not measure the engine.",
          "* *Site email yield*: homepage fetched and an email extracted. **This is the number that matches the reported '~30%'.**", ""]
    for title, data in (("Results (266 sites per arm, one pass)", G),):
        if not data:
            continue
        rows = []
        for arm, d in data.items():
            m = arm_metrics(d["rows"])
            k = int(round(m["n"] * (m["website_fetch_success_pct"] or 0) / 100))
            rows.append((arm, m["n"], wilson(k, m["n"]), m["acquisition_success_pct"], m.get("acquisition_incl_corroborated_pct"), m.get("contact_incl_discovery_hints_pct"), m["site_email_pct"],
                         m["avg_core_completeness_pct"], m["avg_latency_s"], d["wall_s"], m["provider_cost_credits"], m["tokens"]))
        L += [f"### {title}", "", table(["Arm", "Sites", "Website fetch success", "Acquisition strict %", "+corroborated %", "Contact incl. hints %", "Site email %", "Core completeness %", "Avg s/site", "Wall s", "Cost (credits)", "AI tokens"], rows), ""]
        e = data.get("engine")
        if e:
            m = arm_metrics(e["rows"])
            cls = Counter(r["info"].get("class") for r in e["rows"])
            fail = Counter((r["home"].get("category") or "no_result") for r in e["rows"] if not r["home"].get("usable"))
            L += [f"Engine classes: {dict(cls)}. Alternative-source hits: {m['alt_source_hits']} (lookups tried: {m['alt_source_tried']}). Failed homepage fetches by verdict: {dict(fail.most_common())}.", ""]
        allcats = sorted({r["home"].get("category") or "no_result" for d in data.values() for r in d["rows"] if not r["home"].get("usable")})
        L += ["Failed homepage fetches by verdict, per arm (counts):", "", table(["Verdict"] + list(data), [[c] + [sum(1 for r in d["rows"] if not r["home"].get("usable") and (r["home"].get("category") or "no_result") == c) for d in data.values()] for c in allcats]), ""]
    if G:
        L += ["### Field-level extraction (site-derived only; discovery-record values excluded)", ""]
        keys = [("email", lambda i: i.get("email")), ("phone", lambda i: i.get("phone")), ("owner / decision maker", lambda i: i.get("owner")), ("social links", lambda i: i.get("social")), ("address", lambda i: i.get("address"))]
        rows = []
        for arm, d in G.items():
            r = d["rows"]
            rows.append([arm] + [pct(sum(1 for x in r if f(x["info"])), len(r)) for _, f in keys])
        L += [table(["Arm"] + [k for k, _ in keys], rows), ""]
        e = G["engine"]["rows"]
        extra = Counter(f for r in e for f in (r["info"].get("fields") or []))
        L += ["Engine-only fields (per lead, from first-party pages and identity-matched sources, each with source, method, timestamp, confidence and verified/inferred status in `field_provenance`): "
              + ", ".join(f"{k} {pct(extra.get(k, 0), len(e))}" for k in ("description", "services", "industries", "company_size", "technologies", "address", "decision_maker", "social")) + ".", ""]
    em = arm_metrics(G["engine"]["rows"]) if G else {}
    dns = pct(cat.get("dns", 0), n)
    corr = pct(em.get("corroborated", 0), em.get("n", 0)) if em else "n/a"
    L += ["## 3. Honest reading", "",
          "* Website fetch success is about two thirds on this sample for every arm, not 30%. The engine's homepage fetch success is not measurably different from the plain HTTP fast path (the arms' confidence intervals overlap); the engine's added value is classification, no wasted retries on challenged sites, and recovery.",
          "* The ~30% figure matches **email yield from the homepage and linked pages** (about 35% in these runs, not changed by the engine), which is limited by sites that publish only a contact form, not by fetch failures.",
          f"* The 80% target is **not reached on a strict basis ({em.get('acquisition_success_pct')}%)**. Counting leads whose existing discovery contact was confirmed by a second public source gives {em.get('acquisition_incl_corroborated_pct')}%, still under 80%. A large part of the missing share is dead sites (DNS failures alone are {dns} of the audit sample, plus 404 and parked pages) and sites that actively block bots (Cloudflare, SiteGround captcha, Akamai, plain 403). Those are not bypassed. Free alternative sources (Internet Archive snapshot, YellowPages/Superpages cards) supplied a new email or phone for {em.get('alt_recovered_pct')}% of all sites and confirmed an existing one for {corr}; the rest keep only their discovery-record contact.",
          "* Cost: 0 credits and 0 AI tokens in every arm (no paid provider keys were present and the acquisition path calls no LLM). Latency is higher with the engine because recovery waits on rate-limited public directories (3 s spacing per directory domain); `LEADX_ALT_DEADLINE_S` caps it per lead.",
          "* Not exercised: Firecrawl, Serper/SearXNG search, Google Places (no keys or instance), Crawl4AI (not installed; Playwright chromium used instead). They are implemented behind env keys and mocked in tests only.",
          "* Arms ran on different random sites, so differences of a few points between arms are noise; the table gives 95% intervals for fetch success.", ""]
    path = os.path.join(ROOT, "docs", "FETCH_AUDIT.md")
    open(path, "w").write("\n".join(L))
    print("wrote", path)
